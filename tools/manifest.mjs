/* manifest.mjs — write MANIFEST.txt, the list of files a checkout needs.
 *
 * Written because a repository arrived holding eleven of twenty-four core
 * modules, no build script, no interface sources and none of the reference
 * data. Everything committed was current; what was missing had simply never
 * been added, and nothing in the tree said so. The built HTML still opened,
 * which made the gap easy to miss.
 *
 * Generated rather than maintained by hand, so it cannot drift from the tree
 * it describes.
 */
import { readFileSync, writeFileSync, readdirSync, statSync, existsSync } from 'fs';
import { createHash } from 'crypto';

const groups = [
  ['src/core', 'the maths — every module the build inlines', /\.js$/],
  ['src/ui', 'the interface: markup, style and the one script', /\.(html|css|js)$/],
  // .mjs as well as .js: the Phase 1 audit is an .mjs and the manifest
  // silently omitted it, which the audit's own reverse check then caught.
  ['tests', 'validation suite, benchmark and the Phase 1 audit', /\.(js|mjs)$/],
  // .cjs too: the interface test and its page shim are .cjs, and two check
  // stages run them; the manifest left all three out.
  ['tools', 'build helpers, figures, audit, legacy .xls reader, the interface test', /\.(mjs|cjs|py)$/],
  ['docs', 'notes on what was validated and what was not', /\.md$/],
  ['docs', 'figures, generated by tools/make-diagrams.mjs', /\.svg$/],
  ['data/reference', 'production data used for validation', /\.tsv$/],
  // The complete designs: the build embeds two of these files and the suite
  // reads all of them, and the manifest did not list the directory at all.
  ['data/reference/lep', 'complete LEparagliding designs: input, section, the program\'s own output, cut parts',
    /\.(lep|txt|tsv)$/],
];
// LICENSE among them: the repository carries it, and a release that did not
// deleted it on the next commit. package.json too: the build reads the
// release's version from it, and the checks are run through it.
const roots = ['build.py', 'package.json', 'README.md', 'ROADMAP.md', 'CHANGELOG.md', 'LICENSE'];

const lines = [
  'MANIFEST — every file a working checkout needs.',
  '',
  'Generated by tools/manifest.mjs. A tree missing anything below can still',
  'open dist/paraglider-design-tool.html, because that file is self-contained,',
  'but it cannot be rebuilt, tested or audited.',
  '',
];

let total = 0;
let bytes = 0;
const digest = createHash('sha256');

const record = (path) => {
  const body = readFileSync(path);
  digest.update(path);
  digest.update(body);
  total += 1;
  bytes += body.length;
  return body.length;
};

for (const f of roots) {
  if (!existsSync(f)) { lines.push(`  MISSING  ${f}`); continue; }
  lines.push(`  ${String(record(f)).padStart(8)}  ${f}`);
}
lines.push('');

for (const [dir, why, pattern] of groups) {
  if (!existsSync(dir)) { lines.push(`${dir}/  — MISSING ENTIRELY`, ''); continue; }
  const files = readdirSync(dir)
    .filter((f) => pattern.test(f) && statSync(`${dir}/${f}`).isFile())
    .sort();
  lines.push(`${dir}/   ${files.length} files — ${why}`);
  // The reference corpus is long and uniform; list a count and the names.
  if (dir === 'data/reference') {
    for (const f of files) { record(`${dir}/${f}`); }
    lines.push(`  ${files.join(' ')}`.replace(/(.{76}) /g, '$1\n  '));
  } else {
    for (const f of files) {
      lines.push(`  ${String(record(`${dir}/${f}`)).padStart(8)}  ${dir}/${f}`);
    }
  }
  lines.push('');
}

lines.push(`${total} files, ${(bytes / 1024).toFixed(0)} KB`);
lines.push(`sha256 of the tree: ${digest.digest('hex').slice(0, 32)}`);
lines.push('');
lines.push('Verify with:  node tools/audit.mjs');

writeFileSync('MANIFEST.txt', `${lines.join('\n')}\n`);
console.log(`MANIFEST.txt: ${total} files, ${(bytes / 1024).toFixed(0)} KB`);
